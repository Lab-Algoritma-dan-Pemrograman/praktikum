-- Phase 2 identity foundation. Apply only to the fresh Supabase project after
-- staging rehearsal. This migration never changes the legacy project.
create extension if not exists pgcrypto;

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  auth_user_id uuid not null unique references auth.users(id) on delete cascade,
  nim text unique,
  email text not null unique,
  name text not null,
  is_active boolean not null default true,
  hidden boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint users_email_lowercase check (email = lower(email)),
  constraint users_nim_not_empty check (nim is null or length(trim(nim)) > 0)
);

create table if not exists public.roles (
  code text primary key,
  name text not null,
  constraint roles_canonical_code check (code in ('koordinator', 'asisten', 'mahasiswa', 'peminjam'))
);

create table if not exists public.divisions (
  code text primary key,
  name text not null,
  is_active boolean not null default true,
  constraint divisions_canonical_code check (code in ('sekretaris', 'bendahara', 'k3', 'labops', 'pendidikan', 'pdd'))
);

create table if not exists public.permissions (
  code text primary key,
  app text not null,
  description text not null
);

create table if not exists public.role_permissions (
  role_code text not null references public.roles(code) on delete cascade,
  permission_code text not null references public.permissions(code) on delete cascade,
  default_scope jsonb not null default '{}'::jsonb,
  primary key (role_code, permission_code)
);

create table if not exists public.division_permissions (
  division_code text not null references public.divisions(code) on delete cascade,
  permission_code text not null references public.permissions(code) on delete cascade,
  default_scope jsonb not null default '{}'::jsonb,
  primary key (division_code, permission_code)
);

create table if not exists public.user_role_assignments (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  role_code text not null references public.roles(code),
  division_code text references public.divisions(code),
  scope jsonb not null default '{}'::jsonb,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint assignments_division_only_for_asisten check (division_code is null or role_code = 'asisten')
);

create unique index if not exists user_role_assignments_unique_active
  on public.user_role_assignments(user_id, role_code, coalesce(division_code, ''), scope);
create index if not exists user_role_assignments_user_idx on public.user_role_assignments(user_id) where is_active;
create index if not exists user_role_assignments_scope_idx on public.user_role_assignments using gin(scope);

create table if not exists public.user_permission_grants (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  permission_code text not null references public.permissions(code) on delete cascade,
  scope jsonb not null default '{}'::jsonb,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);
create index if not exists user_permission_grants_user_idx on public.user_permission_grants(user_id) where is_active;
create index if not exists user_permission_grants_scope_idx on public.user_permission_grants using gin(scope);

create table if not exists public.auth_sessions (
  id text primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  host text not null,
  token_hash text not null unique,
  csrf_token_hash text not null,
  provider_refresh_token_seal bytea,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  revoked_at timestamptz
);
create index if not exists auth_sessions_user_idx on public.auth_sessions(user_id, created_at desc);
create index if not exists auth_sessions_active_idx on public.auth_sessions(expires_at) where revoked_at is null;

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_id bigint references public.users(id) on delete set null,
  action text not null,
  app text not null,
  subject_type text not null,
  subject_id text not null,
  scope jsonb not null default '{}'::jsonb,
  request_id text not null,
  operation_id text not null,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists audit_logs_created_idx on public.audit_logs(created_at desc);
create index if not exists audit_logs_actor_idx on public.audit_logs(actor_id, created_at desc);
create index if not exists audit_logs_subject_idx on public.audit_logs(subject_type, subject_id, created_at desc);
create index if not exists audit_logs_scope_idx on public.audit_logs using gin(scope);

alter table public.users enable row level security;
alter table public.roles enable row level security;
alter table public.divisions enable row level security;
alter table public.permissions enable row level security;
alter table public.role_permissions enable row level security;
alter table public.division_permissions enable row level security;
alter table public.user_role_assignments enable row level security;
alter table public.user_permission_grants enable row level security;
alter table public.auth_sessions enable row level security;
alter table public.audit_logs enable row level security;

drop policy if exists users_self_select on public.users;
create policy users_self_select on public.users for select to authenticated
  using (auth_user_id = auth.uid());
drop policy if exists users_self_update on public.users;
create policy users_self_update on public.users for update to authenticated
  using (auth_user_id = auth.uid()) with check (auth_user_id = auth.uid());

drop policy if exists roles_no_client_access on public.roles;
create policy roles_no_client_access on public.roles for all to authenticated using (false) with check (false);
drop policy if exists divisions_no_client_access on public.divisions;
create policy divisions_no_client_access on public.divisions for all to authenticated using (false) with check (false);
drop policy if exists permissions_no_client_access on public.permissions;
create policy permissions_no_client_access on public.permissions for all to authenticated using (false) with check (false);
drop policy if exists role_permissions_no_client_access on public.role_permissions;
create policy role_permissions_no_client_access on public.role_permissions for all to authenticated using (false) with check (false);
drop policy if exists division_permissions_no_client_access on public.division_permissions;
create policy division_permissions_no_client_access on public.division_permissions for all to authenticated using (false) with check (false);
drop policy if exists assignments_self_select on public.user_role_assignments;
create policy assignments_self_select on public.user_role_assignments for select to authenticated
  using (user_id in (select id from public.users where auth_user_id = auth.uid()));
drop policy if exists grants_self_select on public.user_permission_grants;
create policy grants_self_select on public.user_permission_grants for select to authenticated
  using (user_id in (select id from public.users where auth_user_id = auth.uid()));
drop policy if exists sessions_self_select on public.auth_sessions;
create policy sessions_self_select on public.auth_sessions for select to authenticated
  using (user_id in (select id from public.users where auth_user_id = auth.uid()));
drop policy if exists audit_no_client_access on public.audit_logs;
create policy audit_no_client_access on public.audit_logs for all to authenticated using (false) with check (false);
